import React from 'react';
import type { Route } from '../App.js';

interface Props {
  active: string;
  onNavigate: (r: Route) => void;
}

export function NavigationRail({ active, onNavigate }: Props) {
  const items = [
    { id: 'home', label: 'Home', icon: HomeIcon, route: { name: 'home' } as Route },
    { id: 'projects', label: 'Projects', icon: ProjectsIcon, route: { name: 'projects' } as Route },
    { id: 'models', label: 'Models', icon: ModelsIcon, route: { name: 'models' } as Route },
    { id: 'settings', label: 'Settings', icon: SettingsIcon, route: { name: 'settings', section: 'general' } as Route },
  ];

  return (
    <nav style={{
      width: 56,
      height: '100vh',
      background: 'var(--surface-app)',
      borderRight: '1px solid var(--line-subtle)',
      display: 'flex',
      flexDirection: 'column',
      alignItems: 'center',
      padding: '12px 0',
      gap: 4,
      flexShrink: 0,
    }}>
      {items.map((item) => {
        const Icon = item.icon;
        const isActive = active === item.id;
        return (
          <button
            key={item.id}
            onClick={() => onNavigate(item.route)}
            title={item.label}
            style={{
              width: 40,
              height: 40,
              borderRadius: 'var(--radius-md)',
              border: 'none',
              background: isActive ? 'var(--brand-tint)' : 'transparent',
              color: isActive ? 'var(--text-brand)' : 'var(--text-muted)',
              cursor: 'pointer',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'center',
              transition: 'background var(--dur-fast)',
            }}
          >
            <Icon size={20} />
          </button>
        );
      })}
    </nav>
  );
}

